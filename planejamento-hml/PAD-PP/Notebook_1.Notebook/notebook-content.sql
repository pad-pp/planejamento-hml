CODIGO_UO AS [Código UO]
FROM VINCULO_ACAO;
GO 

CREATE OR ALTER VIEW dbo.v_OBJETIVO_ESTRATEGICO AS
SELECT OE.CODIGO_OE as [Código], 
CODIGO_PROGRAMA AS [Código Programa],
OE.DESCRICAO  AS [Descrição],
OE.NOME   AS [Nome]
FROM OBJETIVO_ESTRATEGICO OE
INNER JOIN VINCULO_OBJETIVO_ESTRATEGICO VOE ON VOE.CODIGO_OE = OE.CODIGO_OE 
GO

CREATE OR ALTER VIEW dbo.v_BENEFICIARIO AS
SELECT CODIGO_PRODUTO as [Código Produto], 
NOME   AS [Beneficiário]
FROM BENEFICIARIO B INNER JOIN VINCULO_BENEFICIARIO VB 
ON B.CODIGO_BENEFICIARIO = VB.CODIGO_BENEFICIARIO;
GO 

CREATE OR ALTER VIEW dbo.v_PRODUTO_ODS AS
SELECT VO.CODIGO_PRODUTO as [Código Produto], 
VO.CODIGO_ODS   AS [Código ODS],
VO.CODIGO_META_ODS AS [Código Meta],
O.NOME AS [Nome ODS],
MO.NOME AS [Nome Meta]
FROM VINCULO_ODS VO 
INNER JOIN ODS O ON O.CODIGO_ODS = VO.CODIGO_ODS
INNER JOIN META_ODS MO ON O.CODIGO_ODS = MO.CODIGO_ODS
;
GO 




