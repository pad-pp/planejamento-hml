CREATE OR ALTER VIEW dbo.v_ORGAO AS
SELECT
    CONCAT(CODIGO_ORGAO, ' - ', NOME) AS [Código e Nome Órgão],
    CODIGO_ORGAO AS [Código Órgão],
    NOME AS [Nome Órgão],
    NOME_SIMPLIFICADO AS [Nome Órgão Simplificado],
    PODER AS [Poder]
FROM ORGAO;
GO

CREATE OR ALTER VIEW dbo.v_PRODUTO AS
SELECT
    PDT.CLASSIFICACAO AS [Classificação Produto],
    PDT.CODIGO_PRODUTO AS [Código Produto],
    PDT.NOME AS [Nome Produto],
    CAST(PDT.CODIGO_PRODUTO AS VARCHAR(10))
        + ' - ' + PDT.NOME AS [Código e Nome Produto],
    PDT.DESCRICAO AS [Descrição Produto],
    PDT.PRIORITARIO AS [Produto Prioritário],
    PDT.CODIGO_PROGRAMA AS [Código Programa],
    PRG.NOME AS [Nome Programa],
    PDT.ATIVO AS [Status Produto]
FROM PRODUTO AS PDT
LEFT JOIN PROGRAMA AS PRG
    ON PRG.CODIGO_PROGRAMA = PDT.CODIGO_PROGRAMA;
GO

CREATE OR ALTER VIEW dbo.v_PROGRAMA AS
SELECT 
CODIGO_PROGRAMA as [Código Programa],
P.NOME as [Nome Programa],
P.OBJETIVO as [Objetivo Programa],
P.ABRANGENCIA_ESPACIAL as [Abrangência Espacial Programa],
P.CODIGO_ORGAO_RESPONSAVEL as [Código Órgão Responsável Programa], 
P.DIAGNOSTICO as [Diagnóstico Programa],
P.TIPO as [Tipo Programa],
P.CLASSIFICACAO AS [Classificação Programa],
O.NOME AS "Órgão Responsável",
O.PODER AS "Poder Órgão Responsável"

FROM PROGRAMA P INNER JOIN ORGAO O ON P.CODIGO_ORGAO_RESPONSAVEL = O.CODIGO_ORGAO
GO

CREATE OR ALTER VIEW dbo.v_INDICADOR AS
SELECT I.CODIGO_INDICADOR,
I.NOME, 
I.UNIDADE_DE_MEDIDA,
I.TIPO,
I.POLARIDADE, 
I.BASE_GEOGRAFICA,
I.FORMA_DE_TOTALIZACAO_ANUAL,
I.FORMA_DE_TOTALIZACAO_PPA,
I.PERIODICIDADE,
I.META_FINAL_PPA,
I.DESCRICAO,
I.CATEGORIA, 
I.CODIGO_PRODUTO,
I.CODIGO_INDICADOR ||' - '||I.NOME AS "Código e Nome do Indicador", 
I.CODIGO_ORGAO,
I.CODIGO_PROGRAMA,
O.NOME_SIMPLIFICADO, 
I.CODIGO_PROGRAMA || ' - ' || P.NOME AS "Código e Nome do Programa", 
CASE
    WHEN I.META_ANUAL_1 IS NOT NULL THEN 'SIM'
    ELSE 'NÃO' 
END as "possui meta",
I.FONTE,
I.VALOR_LINHA_DE_BASE, 
I.PERIODO_LINHA_DE_BASE,
I.EXPLICACAO_META_PPA
FROM INDICADOR I INNER JOIN ORGAO O ON I.CODIGO_ORGAO = O.CODIGO_ORGAO
INNER JOIN PROGRAMA P ON P.CODIGO_PROGRAMA = I.CODIGO_PROGRAMA

GO

